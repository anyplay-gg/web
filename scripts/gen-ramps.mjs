// Generates packages/tokens/directions.css: the colour roles of the three brand directions of
// checkpoint 1, in OKLCH, gamut-mapped to sRGB hex, with every text-bearing pair SOLVED to its
// contrast target instead of picked by eye. Each value carries its OKLCH source and its measured
// contrast as a comment, so nobody has to guess why a number is what it is.
//
//   node scripts/gen-ramps.mjs          writes the file
//   node scripts/gen-ramps.mjs --check  fails when the file on disk is not what the spec produces
//
// After the owner picks a direction, the winner moves into tokens.css as the one palette and this
// file keeps only its spec.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { apca, oklchToSrgb, solveLightness, srgbToHex, wcag } from "./lib/color.mjs";

const OUT = fileURLToPath(new URL("../packages/tokens/directions.css", import.meta.url));

/**
 * `ink` holds the neutral hue and chroma of the text colours; `n` that of the surfaces. Surfaces are
 * designed (their lightness is the look), text roles are solved against them.
 */
const DIRECTIONS = {
  a: {
    name: "AnyPlay",
    mode: "dark",
    n: { h: 285, c: 0.003 },
    surfaces: { bg: 0.14, surface: 0.178, surface2: 0.218, line: 0.275 },
    ink: { h: 285, c: 0.003, L: 0.97 },
    brand: { h: 38, c: 0.2, L: 0.69, hoverL: 0.74 },
    wash: { L: 0.25, c: 0.06 },
    why: {
      bg: "Neutral near-black (chroma 0.003): the launcher's own chrome is black with white alpha, and the web is its twin. No blue cast, no warm cast, so the brand colour is the only colour on the page.",
      brand:
        "Ember at hue 38: hot and red-leaning, far from every platform colour (PlayStation blue 258, Xbox green 142, Discord 277, Twitch 295) and from the AI-violet band. Used for the mark, focus and the few moments that matter, never as a page wash.",
    },
  },
};

const f = (n, d = 3) => Number(n.toFixed(d));
const lines = [];
const out = (s = "") => lines.push(s);

out(`/* SPDX-License-Identifier: AGPL-3.0-only */`);
out(`/* GENERATED by scripts/gen-ramps.mjs. Do not edit by hand: change the spec and run it again.`);
out(``);
out(`   The colour roles of the three brand directions of checkpoint 1. The data-direction attribute`);
out(`   switches them; direction a is also the default so the app never renders unstyled. After the`);
out(`   owner's pick this file shrinks to one palette inside tokens.css.`);
out(``);
out(`   Every text role is solved to a contrast target against the surface it sits on (WCAG 2.2 ratio`);
out(`   and APCA Lc are printed beside it; scripts/check-contrast.mjs re-measures them from the hex`);
out(`   values below). Surfaces are designed, text is solved, nothing is picked by eye. */`);

const summary = {};

for (const [key, d] of Object.entries(DIRECTIONS)) {
  const dark = d.mode === "dark";
  const col = (L, c, h) => {
    const { rgb, chroma } = oklchToSrgb(L, c, h);
    return { rgb, hex: srgbToHex(rgb), L, c: chroma, h };
  };
  const bg = col(d.surfaces.bg, d.n.c, d.n.h);
  const surface = col(d.surfaces.surface, d.n.c, d.n.h);
  const surface2 = col(d.surfaces.surface2, d.n.c, d.n.h);
  const line = col(d.surfaces.line, d.n.c, d.n.h);
  const ink = col(d.ink.L, d.ink.c, d.ink.h);
  const solved = (c, h, bgc, target, lc = 0) => col(solveLightness(c, h, bgc.rgb, target, lc), c, h);
  const lineStrong = solved(d.n.c, d.n.h, bg, 3.0, 30);
  const ink2 = solved(d.ink.c, d.ink.h, surface2, 7.0, 62);
  const ink3 = solved(d.ink.c, d.ink.h, surface2, 4.6, 48);
  const brand = col(d.brand.L, d.brand.c, d.brand.h);
  const brandHover = col(d.brand.hoverL, d.brand.c, d.brand.h);
  const wash = col(d.wash.L, d.wash.c, d.brand.h);
  const brandText = solved(d.brand.c, d.brand.h, bg, 7.0, 75);
  // The ink on a brand fill: dark on a bright fill. Solved by searching darkness against the fill.
  let brandInk = null;
  {
    let lo = 0.12;
    let hi = 0.6;
    for (let i = 0; i < 40; i++) {
      const mid = (lo + hi) / 2;
      const c = col(mid, 0.03, d.n.h);
      if (wcag(c.rgb, brand.rgb) >= 6.5 && apca(c.rgb, brand.rgb) >= 45) lo = mid;
      else hi = mid;
    }
    brandInk = col(lo, 0.03, d.n.h);
  }
  const focus = solved(d.brand.c, d.brand.h, bg, 4.5, 45);
  const critical = col(dark ? 0.72 : 0.5, 0.17, 25);
  const criticalText = solved(0.15, 25, surface2, 4.8, 60);

  const m = (a, b) => `${wcag(a.rgb, b.rgb).toFixed(2)}:1, Lc ${apca(a.rgb, b.rgb).toFixed(0)}`;
  const o = (c) => `oklch(${f(c.L)} ${f(c.c)} ${f(c.h, 0)})`;
  const sel = key === "a" ? `:root,\n[data-direction="a"]` : `[data-direction="${key}"]`;

  out(``);
  out(`/* ── Direction ${key.toUpperCase()}: ${d.name} (${d.mode}) ──`);
  out(`   Surface: ${d.why.bg}`);
  out(`   Brand: ${d.why.brand} */`);
  out(`${sel} {`);
  out(`  color-scheme: ${d.mode};`);
  const v = (name, c, note) => out(`  --ap-${name}: ${c.hex}; /* ${o(c)}${note ? ` · ${note}` : ""} */`);
  v("bg", bg, "the page");
  v("surface", surface, `panel on bg; the step is lightness only, edges carry the rest`);
  v("surface-2", surface2, `inset / hover surface; ink-3 is solved against this one, the hardest case`);
  v("line", line, "hairline between things; decorative, not a UI boundary");
  v("line-strong", lineStrong, `control borders, solved to 3.0:1 on bg (WCAG 1.4.11): ${m(lineStrong, bg)}`);
  v("ink", ink, `body text on bg ${m(ink, bg)}`);
  v("ink-2", ink2, `secondary text, solved to 7:1 and Lc 62 on surface-2: ${m(ink2, surface2)}`);
  v("ink-3", ink3, `tertiary text (14px and up, never essential), solved to 4.6:1 and Lc 48 on surface-2: ${m(ink3, surface2)}`);
  v("brand", brand, `the AnyPlay colour as a fill; vs bg ${wcag(brand.rgb, bg.rgb).toFixed(2)}:1 (graphic, needs 3)`);
  v("brand-hover", brandHover, "hover of a brand fill: one step away from the page background's direction");
  v("brand-wash", wash, "a tint of the brand for a selected row or badge");
  v("brand-ink", brandInk, `label on a brand fill, solved to 6.5:1 and Lc 45 (labels on it are 17px or larger, weight 600): ${m(brandInk, brand)}`);
  v("brand-text", brandText, `brand colour as text on bg, solved to 7:1 and Lc 75: ${m(brandText, bg)}`);
  v("focus", focus, `focus ring, solved to 4.5:1 and Lc 45 on bg: ${m(focus, bg)}`);
  v("critical", critical, `error fill and icon; vs bg ${wcag(critical.rgb, bg.rgb).toFixed(2)}:1`);
  v("critical-text", criticalText, `error text, solved to 4.8:1 on surface-2: ${m(criticalText, surface2)}`);
  out(`}`);

  summary[key] = {
    bg: bg.hex,
    ink: m(ink, bg),
    ink2: m(ink2, surface2),
    ink3: m(ink3, surface2),
    brandText: m(brandText, bg),
    brandInk: m(brandInk, brand),
    focus: m(focus, bg),
    brandOnBg: wcag(brand.rgb, bg.rgb).toFixed(2),
  };
}

const text = lines.join("\n") + "\n";
if (process.argv.includes("--check")) {
  let disk = "";
  try {
    disk = readFileSync(OUT, "utf8");
  } catch {}
  if (disk !== text) {
    console.error("packages/tokens/directions.css is out of date: run node scripts/gen-ramps.mjs");
    process.exit(1);
  }
  console.log("directions.css matches the spec");
} else {
  writeFileSync(OUT, text);
  console.log(JSON.stringify(summary, null, 2));
}
