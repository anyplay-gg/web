// Turns the display faces into glyph outlines for the wordmarks, so the wordmark is drawn from the
// face (SIL OFL 1.1 allows modified versions as long as the reserved font name is not used for the
// result: the wordmark is artwork, not a font) and still loads no font file. Each glyph is kept
// apart so a wordmark can change one letter: the "gesture" of each direction lives on one glyph.
//
//   node scripts/gen-wordmarks.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { readFileSync } from "node:fs";
import * as fontkit from "fontkit";
import wawoff2 from "wawoff2";

const FONTS = fileURLToPath(new URL("../packages/tokens/fonts/", import.meta.url));
const OUT = fileURLToPath(new URL("../apps/web/src/brand/wordmark-paths.generated.ts", import.meta.url));

const SPECS = {
  a: { file: "bricolage-grotesque-latin.woff2", variation: { wght: 720 }, tracking: -0.01 },
  b: { file: "instrument-sans-latin.woff2", variation: { wght: 650 }, tracking: -0.015 },
  // C sets "Any" wide and "Play" narrow: the width axis is the gesture (any width, one word).
  c: { file: "anybody-latin.woff2", variation: { wght: 840, wdth: 150 }, variationAfter: { wght: 840, wdth: 62 }, split: 3, tracking: 0.02 },
};

const out = {};
// fontkit cannot make a variable instance of a WOFF2 file, so the file is unpacked to TrueType first.
const open = async (file) => fontkit.create(Buffer.from(await wawoff2.decompress(readFileSync(FONTS + file))));
for (const [key, spec] of Object.entries(SPECS)) {
  const base = await open(spec.file);
  const fontA = base.getVariation(spec.variation);
  const fontB = spec.variationAfter ? base.getVariation(spec.variationAfter) : fontA;
  const run = base.layout("AnyPlay");
  const upm = base.unitsPerEm;
  let x = 0;
  const glyphs = [];
  run.glyphs.forEach((g, i) => {
    const pos = run.positions[i];
    const font = i < (spec.split ?? 99) ? fontA : fontB;
    const vg = font.getGlyph(g.id);
    const adv = vg.advanceWidth + (pos.xAdvance - g.advanceWidth);
    const d = vg.path.scale(1, -1).translate(x + pos.xOffset, -pos.yOffset).toSVG();
    glyphs.push({
      char: "AnyPlay"[i],
      d,
      x: Math.round(x),
      advance: Math.round(adv),
      bbox: [vg.bbox.minX, -vg.bbox.maxY, vg.bbox.maxX, -vg.bbox.minY].map(Math.round),
    });
    x += adv + spec.tracking * upm;
  });
  out[key] = {
    upm,
    width: Math.round(x - spec.tracking * upm),
    ascent: Math.round(base.ascent),
    descent: Math.round(base.descent),
    capHeight: Math.round(base.capHeight),
    xHeight: Math.round(base.xHeight),
    glyphs,
  };
}

const text = `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by scripts/gen-wordmarks.mjs from the display faces (SIL OFL 1.1). Do not edit.
// Coordinates are in font units with y pointing down; the baseline is y = 0.

export interface WordmarkGlyph {
  char: string;
  d: string;
  x: number;
  advance: number;
  /** minX, minY, maxX, maxY with y down. */
  bbox: [number, number, number, number];
}
export interface WordmarkData {
  upm: number;
  width: number;
  ascent: number;
  descent: number;
  capHeight: number;
  xHeight: number;
  glyphs: WordmarkGlyph[];
}

export const WORDMARK_PATHS: Record<"a" | "b" | "c", WordmarkData> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(OUT, text);
for (const [k, v] of Object.entries(out)) console.log(k, "upm", v.upm, "width", v.width, "cap", v.capHeight, "x", v.xHeight, "glyphs", v.glyphs.map((g) => g.char + g.bbox.join(",")).join(" | "));
